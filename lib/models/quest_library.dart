import 'game_engine.dart';

class LibraryQuest {
  final String id;
  final String name;
  final QuestCategory category;
  final DifficultyGrade difficulty;
  final String description;
  final HunterStat stat;
  final int target;
  final String unit;
  final String repeatable; // 'daily' | 'weekly' | 'always'

  const LibraryQuest({
    required this.id,
    required this.name,
    required this.category,
    required this.difficulty,
    required this.description,
    required this.stat,
    required this.target,
    required this.unit,
    this.repeatable = 'daily',
  });

  Quest toQuest() {
    return Quest(
      id: '${id}_${DateTime.now().millisecondsSinceEpoch}',
      name: name,
      description: description,
      difficulty: difficulty,
      category: category,
      stat: stat,
      progress: 0,
      target: target,
      completed: false,
      xpReward: difficultyXp[difficulty] ?? 20,
      statXpReward: difficultyStatXp[difficulty] ?? 10,
      isCustom: false,
    );
  }
}

